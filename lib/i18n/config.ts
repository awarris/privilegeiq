export const dictionaries = { en, fr };

export function normalizeLocale(value: string | null | undefined): Locale {
  return value === "fr" ? "fr" : DEFAULT_LOCALE;
}

export function getDictionary(locale: Locale) {
  return dictionaries[locale];
}

export function translateEnum(value: string, locale: Locale): string {
  return getDictionary(locale).enumLabels[value] ?? value
    .toLowerCase()
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

export function translateRoleDescription(slug: string, fallback: string | null, locale: Locale): string {
  return getDictionary(locale).roleDescriptions[slug] ?? fallback ?? "";
}

export function translatePermissionName(slug: string, fallback: string, locale: Locale): string {
  return getDictionary(locale).permissionNames[slug] ?? fallback;
}

export function getRiskPresentation(
  risk: {
    type: string;
    severity: string;
    user: { name: string; lastActiveAt?: Date | string | null };
    permission?: { slug: string } | null;
  },
  locale: Locale,
): { title: string; description: string } {
  const dictionary = getDictionary(locale);
  const riskContent = dictionary.riskContent;

  if (risk.type === "SENSITIVE_PERMISSION") {
    return {
      title: riskContent.SENSITIVE_PERMISSION,
      description: riskContent.sensitiveDescription(
        risk.user.name,
        risk.permission?.slug ?? "unknown permission",
        translateEnum(risk.severity, locale),
      ),
    };
  }

  if (risk.type === "INACTIVE_ACCOUNT") {
    const lastActiveAt = risk.user.lastActiveAt ? new Date(risk.user.lastActiveAt) : null;
    const days = lastActiveAt
      ? Math.max(0, Math.floor((Date.now() - lastActiveAt.getTime()) / 86_400_000))
      : 0;

    return {
      title: riskContent.INACTIVE_ACCOUNT,
      description: riskContent.inactiveDescription(risk.user.name, days),
    };
  }

  return {
    title: riskContent.EXCESSIVE_PRIVILEGES,
    description: riskContent.excessiveDescription(risk.user.name),
  };
}
